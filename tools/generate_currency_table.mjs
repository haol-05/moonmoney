// Regenerates currency_table.mbt from the two public data sets.
//
//   node tools/generate_currency_table.mjs
//
// Sources (see SOURCES.md for the full provenance and licences):
//
//   * datasets/currency-codes
//       alphabetic code, numeric code, minor unit and ISO name
//   * unicode-org/cldr-json
//       display digits, cash digits, cash rounding step and symbol
//
// Both are read through jsDelivr, which serves the same bytes as
// raw.githubusercontent.com and is reachable from more networks. The output is
// deterministic: the same inputs always produce the same file, sorted by code.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const SOURCES = {
  codes: "https://cdn.jsdelivr.net/gh/datasets/currency-codes@main/data/codes-all.csv",
  symbols:
    "https://cdn.jsdelivr.net/gh/unicode-org/cldr-json@main/cldr-json/cldr-numbers-full/main/en/currencies.json",
  fractions:
    "https://cdn.jsdelivr.net/gh/unicode-org/cldr-json@main/cldr-json/cldr-core/supplemental/currencyData.json",
};

/// A minimal RFC 4180 reader: the ISO list has quoted fields containing commas,
/// so splitting on commas would shift every later column.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          quoted = false;
        }
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (ch !== "\r") {
      field += ch;
    }
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((cell) => cell.trim().length > 0));
}

const escape = (text) => text.replace(/\\/g, "\\\\").replace(/"/g, '\\"');

async function getJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} returned ${response.status}`);
  return response.json();
}

async function main() {
  const codesText = await (await fetch(SOURCES.codes)).text();
  const symbols = (await getJson(SOURCES.symbols)).main.en.numbers.currencies;
  const fractions = (await getJson(SOURCES.fractions)).supplemental.currencyData.fractions;

  const active = new Map();
  for (const fields of parseCsv(codesText.replace(/^\uFEFF/, "")).slice(1)) {
    const code = (fields[2] ?? "").trim();
    const withdrawn = (fields[5] ?? "").trim();
    if (!/^[A-Z]{3}$/.test(code) || withdrawn) continue;
    if (!active.has(code)) {
      active.set(code, {
        name: (fields[1] ?? "").trim(),
        numeric: (fields[3] ?? "").trim(),
        minor: (fields[4] ?? "").trim(),
      });
    }
  }

  const rows = [];
  for (const [code, info] of [...active].sort((a, b) => a[0].localeCompare(b[0]))) {
    // Currencies without an ISO minor unit carry no fixed scale, so no
    // fixed-point amount can be formed from them.
    if (!/^\d+$/.test(info.minor)) continue;
    const exponent = Number(info.minor);
    const fraction = fractions[code] ?? {};
    const digits = fraction._digits !== undefined ? Number(fraction._digits) : null;
    const display = digits ?? exponent;
    const cashExponent =
      fraction._cashDigits !== undefined ? Number(fraction._cashDigits) : display;
    const cashStep =
      fraction._cashRounding !== undefined && Number(fraction._cashRounding) > 0
        ? Number(fraction._cashRounding)
        : 1;
    const name = symbols[code]?.displayName?.trim() || info.name || code;
    const symbol = (symbols[code]?.symbol ?? "").trim();
    rows.push({ code, numeric: info.numeric === "" ? 0 : Number(info.numeric), exponent, display, cashExponent, cashStep, name, symbol });
  }

  const body = rows
    .map(
      (r) =>
        `  row("${r.code}", ${r.numeric}, ${r.exponent}, ${r.display}, ${r.cashExponent}, ${r.cashStep}, "${escape(r.name)}", "${escape(r.symbol)}"),`,
    )
    .join("\n");

  const header = `// ISO 4217 currency table: ${rows.length} currencies.
//
// Generated by \`tools/generate_currency_table.mjs\`; do not edit by hand.
// See SOURCES.md for the data sets, their versions and their licences.
//
//   * alphabetic code, numeric code, minor unit and name
//       datasets/currency-codes (derived from ISO 4217, PDDL-1.0)
//   * display digits, cash digits, cash rounding step and symbol
//       Unicode CLDR, unicode-org/cldr-json (Unicode License v3)
//
// ISO 4217 minor units (\`exponent\`) and CLDR display digits disagree for the
// currencies whose smallest unit is no longer in circulation, HUF and AFN among
// them. Both are kept: \`exponent\` is the exactness boundary an amount is stored
// with, \`display_digits\` is what CLDR recommends for a display.
//
// Currencies that have no ISO 4217 minor unit are deliberately absent: the
// metals (XAU, XAG, XPT, XPD), the special drawing right (XDR), the fund and
// testing codes (XBA..XBD, XSU, XUA, XTS) and \`XXX\`. They carry no defined
// number of decimal places, so a fixed-point amount cannot be formed from them
// without inventing one. Build them with \`Currency::custom\` when needed.
//
// The table is sorted by alphabetic code, which is the order \`Currency::all\`
// and \`Currency::known_codes\` report, so listings stay stable across runs.

///|
/// One table row. A function rather than a struct literal so that the table
/// below reads as one line per currency.
fn row(
  code : String,
  numeric : Int32,
  exponent : Int32,
  display_digits : Int32,
  cash_exponent : Int32,
  cash_step : Int32,
  name : String,
  symbol : String,
) -> Currency {
  {
    code,
    numeric,
    exponent,
    display_digits,
    cash_exponent,
    cash_step,
    name,
    symbol,
  }
}

///|
let table : Array[Currency] = [
${body}
]
`;

  const target = join(dirname(fileURLToPath(import.meta.url)), "..", "currency_table.mbt");
  writeFileSync(target, header, "utf8");
  console.log(`wrote ${rows.length} currencies to ${target}`);
}

await main();
